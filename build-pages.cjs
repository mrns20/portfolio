const fs = require('node:fs');
const path = require('node:path');
const names = ['index.html', 'about.html', 'work.html', 'research.html', 'contact.html'];
const pages = Object.fromEntries(names.map(name => [name, fs.readFileSync(path.join(__dirname, name), 'utf8')]));
fs.writeFileSync(path.join(__dirname, 'page-data.js'), '// Generated by node build-pages.cjs after editing page HTML.\nwindow.portfolioPages = ' + JSON.stringify(pages) + ';\n');

// Bundle the CV so downloads also work when the portfolio is opened from disk.
const cv = fs.readFileSync(path.join(__dirname, 'assets/cv-marino-tselani.pdf')).toString('base64');
fs.appendFileSync(path.join(__dirname, 'page-data.js'), 'window.portfolioCvBase64 = ' + JSON.stringify(cv) + ';\n');